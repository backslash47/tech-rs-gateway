#pragma once

#include <cstddef>
#include <cstdint>
#include <utility>
#include <vector>

namespace tech_rs_gateway {
using Bytes = std::vector<uint8_t>;

/**
 * @brief Computes CRC-16/MCRF4XX (poly 0x8408, init 0xffff, xorout 0).
 * @param data Readable buffer of at least length bytes.
 * @param length Number of bytes to checksum.
 * @return Numeric CRC; the protocol transmits its two octets big-endian.
 */
uint16_t crc16(const uint8_t* data, size_t length);

/**
 * @brief Reads a big-endian 16-bit value.
 * @param p Pointer to at least two readable bytes.
 * @return Decoded unsigned word.
 */
inline uint16_t word(const uint8_t* p) {
    return uint16_t(p[0]) << 8 | p[1];
}

/**
 * @brief Appends a 16-bit value in big-endian wire order.
 * @param out Destination byte vector, extended by two octets.
 * @param value Unsigned value to encode.
 */
inline void append_word(Bytes& out, uint16_t value) {
    out.push_back(uint8_t(value >> 8));
    out.push_back(uint8_t(value));
}

/// An outer protocol field; value excludes framing and alignment padding.
struct Tlv {
    uint16_t tag;
    Bytes value;
};

/// Decoded Internet envelope, containing either a bootstrap code or ordinary fields.
struct Frame {
    uint16_t address = 0;
    bool bootstrap = false;
    bool recovery = false; ///< Captured truncated-route recovery envelope.
    uint16_t bootstrap_code = 0;
    std::vector<Tlv> fields;
};

/**
 * @brief Validates one complete Internet-module envelope, including CRC and lengths.
 * @param packet Exactly one frame; no serial chunk reassembly is performed here.
 * @param[out] result Replaced only on successful decoding; unchanged on failure.
 * @return true for a valid envelope, false for malformed or unsupported framing.
 * @note Checks end markers at structural boundaries, not inside values. This
 * decoder does not implement the legacy FFFA register bus.
 */
bool decode(const Bytes& packet, Frame& result);

/**
 * @brief Encodes ordinary TLV fields with zero padding, trailer and CRC.
 * @param address Two-byte protocol address.
 * @param fields Fields in wire order; each value must fit a 16-bit length.
 * @return Complete packet, or an empty vector for no fields or an oversized value.
 * @note Short bootstrap forms are not generated by this function.
 */
Bytes encode(uint16_t address, const std::vector<Tlv>& fields);

/**
 * @brief Encodes the short Internet bootstrap envelope with CRC.
 * @param address Two-byte role address; the runtime uses protocol::INTERNET_ADDRESS.
 * @param code Bootstrap code: 0 for the initial request or 0x0101 for its response.
 * @return Owned complete packet.
 * @note The caller supplies a recognized code; this encoder does not validate it.
 */
Bytes encode_bootstrap(uint16_t address, uint16_t code);

/** @brief Reassembles Internet packets using structural lengths, not payload markers. */
class FrameStream {
  public:
    /**
     * @brief Reassembles complete Internet frames from an arbitrary serial chunk.
     * @param incoming Octets in wire order; input may contain partial or multiple packets.
     * @param now Current monotonic time in milliseconds (uint32_t, not wall-clock time).
     * @return Owned decoded frames in order; malformed packets are discarded during
     * resynchronization.
     * @note A frame gap clears partial input. Parsing follows field lengths rather than header-like
     * payload bytes; use from one thread.
     */
    std::vector<Frame> feed(const Bytes& incoming, uint32_t now);
    /**
     * @brief Clears partial input and the inter-byte-gap timestamp without emitting frames.
     */
    void reset();

  private:
    Bytes buffer_;
    uint32_t last_rx_ = 0;
    // Zero means incomplete; SIZE_MAX means malformed.
    size_t frame_size() const;
    void drain(std::vector<Frame>& output);
};
} // namespace tech_rs_gateway
